export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed" });
  }

  const { text } = req.body || {};

  if (!text || text.trim().length < 20) {
    return res.status(400).json({ error: "Слишком короткое описание" });
  }

  return res.status(200).json({
    result: {
      summary:
        "По описанию заметны признаки тревожного напряжения, нарушения сна, усталости и трудностей с концентрацией.",
      clusters: [
        "Тревога / напряжение",
        "Сон / истощение",
        "Концентрация / исполнительные функции"
      ],
      risk: "medium",
      questions: [
        "Как давно продолжается это состояние?",
        "Бывали ли мысли, что жить не хочется или причинить себе вред?",
        "Насколько это мешает работе, отношениям и обычной жизни?"
      ],
      recommendation:
        "Рекомендуется консультация специалиста в ближайшие дни. Если появляются мысли о самоповреждении, ощущение потери контроля или резкое ухудшение — нужна срочная помощь."
    }
  });
}
