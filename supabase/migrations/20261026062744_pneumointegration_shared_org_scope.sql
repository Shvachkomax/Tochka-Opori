-- Shared Production database tenancy for partner deployments.
-- Legacy rows stay tenant_id = NULL and remain visible to the default app;
-- partner deployments receive only rows written under their server-side org id.

ALTER TABLE public.service_requests
  ADD COLUMN IF NOT EXISTS tenant_id text;

CREATE INDEX IF NOT EXISTS service_requests_tenant_module_created_idx
  ON public.service_requests (tenant_id, module, created_at DESC);

CREATE TABLE IF NOT EXISTS public.crisis_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  status text DEFAULT 'new',
  priority text DEFAULT 'urgent',
  crisis_text text,
  contact text,
  source text,
  environment text,
  public_code text,
  session_id text,
  high_risk_detected boolean DEFAULT false,
  risk_markers jsonb,
  admin_comment text,
  handled_by text,
  handled_at timestamptz,
  json_data jsonb,
  tenant_id text
);

ALTER TABLE public.crisis_requests
  ADD COLUMN IF NOT EXISTS tenant_id text;

CREATE INDEX IF NOT EXISTS crisis_requests_status_idx
  ON public.crisis_requests (status);
CREATE INDEX IF NOT EXISTS crisis_requests_created_at_idx
  ON public.crisis_requests (created_at DESC);
CREATE INDEX IF NOT EXISTS crisis_requests_tenant_created_idx
  ON public.crisis_requests (tenant_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.expert_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  email text,
  telegram text,
  role text NOT NULL,
  specialty text,
  city text,
  organization text,
  comment text,
  status text DEFAULT 'pending',
  created_at timestamptz DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by text,
  reviewer_comment text,
  tenant_id text
);

ALTER TABLE public.expert_requests
  ADD COLUMN IF NOT EXISTS tenant_id text;

ALTER TABLE public.expert_requests
  ADD COLUMN IF NOT EXISTS tenant_id text;

CREATE INDEX IF NOT EXISTS expert_requests_status_idx
  ON public.expert_requests (status);
CREATE INDEX IF NOT EXISTS expert_requests_tenant_created_idx
  ON public.expert_requests (tenant_id, created_at DESC);

-- The API uses the server-only Supabase credential for these records.
-- Explicit grants are required for projects that do not expose new tables by default.
ALTER TABLE public.crisis_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expert_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.crisis_requests FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.expert_requests FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.crisis_requests TO service_role;
GRANT ALL ON TABLE public.expert_requests TO service_role;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'crisis_requests'
      AND policyname = 'crisis_requests_service_role_only'
  ) THEN
    CREATE POLICY crisis_requests_service_role_only
      ON public.crisis_requests FOR ALL TO service_role
      USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'expert_requests'
      AND policyname = 'expert_requests_service_role_only'
  ) THEN
    CREATE POLICY expert_requests_service_role_only
      ON public.expert_requests FOR ALL TO service_role
      USING (true) WITH CHECK (true);
  END IF;
END;
$$;

