async function getBodyCapabilitiesContext(supabase, ownerId) {
  const context = {};

  // Check for today's log
  const today = new Date().toISOString().slice(0, 10);
  const { count: todayCount } = await supabase
    .from("body_daily_logs")
    .select("*", { count: "exact", head: true })
    .eq("owner_id", ownerId)
    .eq("log_date", today);
  context.has_today_log = (todayCount || 0) > 0;

  // History count
  const { count: historyCount } = await supabase
    .from("body_daily_logs")
    .select("*", { count: "exact", head: true })
    .eq("owner_id", ownerId);
  context.history_count = historyCount || 0;

  // Plate count
  const { count: plateCount } = await supabase
    .from("body_plate_photos")
    .select("*", { count: "exact", head: true })
    .eq("owner_id", ownerId);
  context.plate_count = plateCount || 0;

  // Weekly summary exists
  const { count: weeklyCount } = await supabase
    .from("body_weekly_summaries")
    .select("*", { count: "exact", head: true })
    .eq("owner_id", ownerId);
  context.has_weekly_summary = (weeklyCount || 0) > 0;

  // Specialist relation
  context.has_specialist = false;

  // Available sections
  context.available_sections = [
    "diary", "charts", "plate", "weekly", "insights",
    "ai_companion", "specialist_request", "profile", "access",
  ];
  context.service_request_available = true;

  return context;
}

